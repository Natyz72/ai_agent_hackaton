import json
from typing import Any
import httpx
from app.config import settings
from app.llm.base import LLMClient, LLMResponse, ToolCall


class GeminiClient(LLMClient):
    """
    Production Gemini 2.0 API Client using direct HTTP REST requests.
    Secrets and API keys remain strictly server-side.
    """

    def __init__(self, api_key: str | None = None, model: str | None = None):
        self.api_key = api_key or settings.gemini_api_key
        self.model = model or settings.gemini_model

    async def generate_response(
        self,
        messages: list[dict[str, Any]],
        tools: list[dict[str, Any]] | None = None,
        system_instruction: str | None = None,
    ) -> LLMResponse:
        if not self.api_key:
            raise ValueError("GEMINI_API_KEY is not configured on server")

        url = f"https://generativelanguage.googleapis.com/v1beta/models/{self.model}:generateContent?key={self.api_key}"

        # Format contents for Gemini REST API
        contents = []
        for m in messages:
            role = m.get("role", "user")
            parts = []
            if m.get("content"):
                parts.append({"text": m["content"]})
            if m.get("tool_calls"):
                role = "model"
                for tc in m["tool_calls"]:
                    parts.append({
                        "functionCall": {
                            "name": tc["name"],
                            "args": tc.get("args", {}),
                        }
                    })
            if m.get("tool_response"):
                # Gemini functionResponse requires role: user
                role = "user"
                resp_val = m["tool_response"]
                if isinstance(resp_val, str):
                    try:
                        resp_val = json.loads(resp_val)
                    except Exception:
                        resp_val = {"result": resp_val}
                elif not isinstance(resp_val, dict):
                    resp_val = {"result": resp_val}
                parts.append({
                    "functionResponse": {
                        "name": m.get("tool_name", "tool"),
                        "response": resp_val,
                    }
                })
            if parts:
                contents.append({"role": role, "parts": parts})

        payload: dict[str, Any] = {"contents": contents}

        if system_instruction:
            payload["systemInstruction"] = {
                "parts": [{"text": system_instruction}]
            }

        if tools:
            payload["tools"] = [{"functionDeclarations": tools}]

        async with httpx.AsyncClient(timeout=settings.request_timeout_seconds) as client:
            resp = await client.post(url, json=payload)
            if resp.status_code != 200:
                raise RuntimeError(f"Gemini API error ({resp.status_code}): {resp.text}")
            data = resp.json()

        # Parse response candidates
        candidates = data.get("candidates", [])
        if not candidates:
            return LLMResponse(content="No response generated by model")

        candidate = candidates[0]
        content_parts = candidate.get("content", {}).get("parts", [])

        text_parts = []
        tool_calls: list[ToolCall] = []

        for p in content_parts:
            if "text" in p:
                text_parts.append(p["text"])
            if "functionCall" in p:
                fc = p["functionCall"]
                tool_calls.append(
                    ToolCall(
                        name=fc.get("name", ""),
                        arguments=fc.get("args", {}),
                    )
                )

        combined_text = "\n".join(text_parts).strip() if text_parts else None
        return LLMResponse(content=combined_text, tool_calls=tool_calls)
